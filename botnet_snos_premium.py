async def extract_username_and_message_id2(message_url):
    # Убираем query string если есть
    message_url = message_url.split('?')[0].rstrip('/')
    path = message_url[len('https://t.me/'):].split('/')
    if len(path) == 2:
        # Обычный формат: t.me/username/123
        chat_username = path[0]
        message_id = int(path[1])
        return chat_username, message_id
    elif len(path) == 3:
        # Форум/тред: t.me/group/thread_id/message_id
        chat_username = path[0]
        message_id = int(path[2])
        return chat_username, message_id
    raise ValueError("Неверная ссылка!")

def format_log_line(session, message_url, status):
    now = now_msk().strftime("%H:%M:%S")
    return f"[{now}] {session}.session -> {message_url} - [{status}]"

async def _report_one_session_prem(session, chat_username, message_id, message_url, whitelist, target_ref, peer_ref):
    """Параллельная отправка жалобы от одной премиум-сессии."""
    random_api = random.choice(API)
    api_id, api_hash = random_api.split(":", 1)
    random_reason = random.choice(reasons)
    random_reason_text = random.choice(reasons_texts)

    print(f"[PREM] [{session}] Подключаемся (api_id={api_id})...", flush=True)

    client = TelegramClient(
        f"./prem_sessions/{session}", int(api_id), api_hash,
        system_version='4.16.30-vxCUSTOM'
    )
    try:
        connected = False
        for db_attempt in range(3):
            try:
                await asyncio.wait_for(client.connect(), timeout=12)
                connected = True
                break
            except (asyncio.TimeoutError, OSError):
                if db_attempt == 2:
                    print(f"[PREM] [{session}] ❌ ОШИБКА СОЕДИНЕНИЯ (timeout)", flush=True)
                    return "ОШИБКА СОЕДИНЕНИЯ", None
                await asyncio.sleep(1)
            except Exception as e:
                if "database is locked" in str(e) and db_attempt < 2:
                    await asyncio.sleep(random.uniform(1, 2))
                else:
                    raise
        if not connected:
            return "ОШИБКА СОЕДИНЕНИЯ", None

        if not await client.is_user_authorized():
            print(f"[PREM] [{session}] ❌ НЕВАЛИД (не авторизован)", flush=True)
            return "НЕВАЛИД", None

        try:
            chat = await client.get_entity(chat_username)
            if peer_ref[0] is None:
                peer_ref[0] = chat.id
        except Exception as e:
            if peer_ref[0] is not None and "No user has" in str(e):
                chat = await client.get_entity(peer_ref[0])
            else:
                raise
        print(f"[PREM] [{session}] ✅ Подключён, чат получен: {chat_username}", flush=True)

        if target_ref[0] is None:
            msg = await client.get_messages(chat, ids=message_id)
            if msg is not None and msg.from_id is not None:
                try:
                    user_entity = await client.get_entity(msg.from_id)
                    target_ref[0] = msg.from_id.user_id if isinstance(msg.from_id, PeerUser) else "?"
                    target_ref[1] = user_entity.username or "Нет username"
                    print(f"[PREM] [{session}] 🎯 Таргет определён: ID={target_ref[0]}, *@{target_ref[1]}*", flush=True)
                    if target_ref[0] in whitelist:
                        print(f"[PREM] [{session}] 🍕 WHITELIST — таргет в белом списке", flush=True)
                        return "WHITELIST", None
                except Exception:
                    target_ref[0] = "anon"
                    target_ref[1] = "Анонимный"
            else:
                # Анонимный пост или канальное сообщение — продолжаем репорт
                target_ref[0] = "anon"
                target_ref[1] = "Анонимный"
                print(f"[PREM] [{session}] ⚠️ from_id=None (анонимный/канал) — продолжаем репорт", flush=True)

        # Получаем список причин от сервера динамически (3-шаговый флоу)
        try:
            # Шаг 1: получаем категории
            print(f"[PREM] [{session}] 📤 Шаг 1: запрашиваем категории жалоб...", flush=True)
            r1 = await client(ReportRequest(peer=chat, id=[message_id], option=b'', message=''))
            print(f"[PREM] [{session}] 📥 Шаг 1 ответ: {type(r1).__name__} | options={[o.option for o in r1.options] if hasattr(r1, 'options') and r1.options else 'нет'}", flush=True)
            if hasattr(r1, 'options') and r1.options:
                cat = random.choice(r1.options).option
                print(f"[PREM] [{session}] 📤 Шаг 2: выбрана категория {cat!r}", flush=True)
            else:
                cat = random_reason
                print(f"[PREM] [{session}] 📤 Шаг 2: категории не получены, используем fallback {cat!r}", flush=True)

            # Шаг 2: выбираем категорию — может вернуть подкатегории
            r2 = await client(ReportRequest(peer=chat, id=[message_id], option=cat, message=''))
            print(f"[PREM] [{session}] 📥 Шаг 2 ответ: {type(r2).__name__} | options={[o.option for o in r2.options] if hasattr(r2, 'options') and r2.options else 'нет'}", flush=True)
            if hasattr(r2, 'options') and r2.options:
                sub = random.choice(r2.options).option
                print(f"[PREM] [{session}] 📤 Шаг 3: выбрана подкатегория {sub!r}, отправляем текст...", flush=True)
                r3 = await client(ReportRequest(peer=chat, id=[message_id], option=sub, message=random_reason_text))
                print(f"[PREM] [{session}] 📥 Шаг 3 ответ: {type(r3).__name__} | result={r3}", flush=True)
            else:
                print(f"[PREM] [{session}] 📤 Шаг 3: подкатегорий нет, отправляем с текстом напрямую...", flush=True)
                r3 = await client(ReportRequest(peer=chat, id=[message_id], option=cat, message=random_reason_text))
                print(f"[PREM] [{session}] 📥 Шаг 3 ответ: {type(r3).__name__} | result={r3}", flush=True)
        except Exception as report_err:
            print(f"[PREM] [{session}] ⚠️ Ошибка в 3-шаговом флоу ({report_err!s:.60}), используем fallback...", flush=True)
            r_fb = await client(ReportRequest(peer=chat, id=[message_id], option=random_reason, message=random_reason_text))
            print(f"[PREM] [{session}] 📥 Fallback ответ: {type(r_fb).__name__} | result={r_fb}", flush=True)
        await asyncio.sleep(random.uniform(0.05, 0.5))
        print(f"[PREM] [{session}] ✅ ДОСТАВЛЕНО", flush=True)
        return "ДОСТАВЛЕНО", None

    except FloodWaitError as e:
        print(f"[PREM] [{session}] 🌊 FLOOD — ждать {e.seconds}с", flush=True)
        return "FLOOD", e.seconds
    except Exception as e:
        if "Could not find" in str(e):
            print(f"[PREM] [{session}] ❌ NOT_FOUND — {e!s:.80}", flush=True)
            return "NOT_FOUND", None
        print(f"[PREM] [{session}] ❌ ОШИБКА — {e!s:.80}", flush=True)
        return f"ОШИБКА: {str(e)[:50]}", None
    finally:
        if client.is_connected():
            await client.disconnect()


async def main2(chat_username, message_id, user, username, message_url, _log_user=None, silent: bool = False):
    # Получаем вайтлист из PostgreSQL (db.py)
    try:
        import db as db_module
        whitelist = await db_module.get_whitelist()
    except Exception as e:
        print(f"[PREM] Ошибка получения вайтлиста: {e}", flush=True)
        whitelist = []

    if "_" in username:
        username = "None"

    print(f"\n{'='*50}", flush=True)
    print(f"[PREM] 🚀 Запуск премиум-ботнета", flush=True)
    print(f"[PREM] 👤 Пользователь: {user} (*@{username}*)", flush=True)
    print(f"[PREM] 🔗 Ссылка: {message_url}", flush=True)
    _sessions = _get_sessions()
    print(f"[PREM] 📦 Сессий загружено: {len(_sessions)}", flush=True)
    print(f"{'='*50}", flush=True)

    target_ref = [None, "Неизвестный пользователь"]
    peer_ref = [None]

    # Запускаем сессии пачками по 8 с задержкой 3-5 сек между пачками
    BATCH_SIZE = 8
    results = []
    pb = ProgressBar(bot, user, total=len(_sessions), title="👑 *Ботнет Премиум*", silent=silent)
    await pb.start()
    done_count = 0
    for i in range(0, len(_sessions), BATCH_SIZE):
        batch = _sessions[i:i + BATCH_SIZE]
        batch_tasks = [_report_one_session_prem(s, chat_username, message_id, message_url, whitelist, target_ref, peer_ref) for s in batch]
        batch_results = await asyncio.gather(*batch_tasks, return_exceptions=True)
        results.extend(zip(batch, batch_results))
        done_count += len(batch)
        await pb.update(done_count)
        if i + BATCH_SIZE < len(_sessions):
            delay = random.uniform(3, 5)
            print(f"[PREM] ⏳ Пачка {i//BATCH_SIZE + 1} завершена, ждём {delay:.1f}с перед следующей...", flush=True)
            await asyncio.sleep(delay)
    await pb.finish()

    valid, ne_valid, flood = 0, 0, 0
    log_lines = [
        "Brown V2 log | botnet-method [PREMIUM]",
        "-" * 42,
        f"Пользователь: {user} (*@{username}*)",
        f"Ссылка: {message_url}",
        "-" * 42
    ]

    for session, result in results:
        if isinstance(result, Exception):
            ne_valid += 1
            print(f"[PREM] [{session}] 💥 ИСКЛЮЧЕНИЕ: {str(result)[:80]}", flush=True)
            log_lines.append(format_log_line(session, message_url, f"ИСКЛЮЧЕНИЕ: {str(result)[:50]}"))
            continue

        status, flood_sec = result

        if status == "WHITELIST":
            print(f"[PREM] ⛔ Таргет в вайтлисте, прерываем", flush=True)
            if not silent:
                await bot.send_message(user, "🍕 *Какая-то ошибка!*", parse_mode="Markdown", reply_markup=keyboards.main_menu)
                try:
                    await bot.send_message(target_ref[0], f"⚠️ *Попытка жалобы на* [сообщение]({message_url}) *от ID {user}!*", parse_mode="Markdown", disable_web_page_preview=True)
                except:
                    pass
            return (0, len(_sessions))
        elif status in ("NO_ID", "NOT_FOUND"):
            ne_valid += 1
            log_lines.append(format_log_line(session, message_url, status))
        elif status == "ДОСТАВЛЕНО":
            valid += 1
            log_lines.append(format_log_line(session, message_url, "ДОСТАВЛЕНО"))
        elif status == "FLOOD":
            flood += 1
            log_lines.append(format_log_line(session, message_url, f"FLOOD {flood_sec}s"))
        else:
            ne_valid += 1
            log_lines.append(format_log_line(session, message_url, status))

    TARGET = target_ref[0]
    target_username = target_ref[1]

    print(f"\n[PREM] {'='*50}", flush=True)
    print(f"[PREM] 🏁 Итоги:", flush=True)
    print(f"[PREM] 🎯 Таргет: ID={TARGET}, *@{target_username}*", flush=True)
    print(f"[PREM] ✅ Доставлено: {valid}", flush=True)
    print(f"[PREM] ❌ Не доставлено: {ne_valid}", flush=True)
    print(f"[PREM] 🌊 Флудов: {flood}", flush=True)
    print(f"[PREM] {'='*50}\n", flush=True)

    log_lines.append("-" * 42)
    log_lines.append("[TARGET]")
    log_lines.append(f"ID: {TARGET}")
    log_lines.append(f"USERNAME: *@{target_username}*")
    log_lines.append("-" * 42)
    log_lines.append(f"Успешно: {valid}")
